# ── Video helper ──────────────────────────────────────────────────────────────

class VideoRecorder:
    """Capture RGB frames via isaaclab.sensors.Camera and write to MP4.

    Architecture (tensor-pose design — supersedes single-prim cached-op):
        /World/VideoCamera   (isaaclab.sensors.Camera prim, top-level)

        Per frame, we call self.camera.set_world_poses_from_view(eyes,
        targets) to push the new camera pose. This is Isaac Lab's
        tensor-based API which writes the pose DIRECTLY to the GPU
        camera buffer the render product reads from. USD is updated as
        a side-effect, but we no longer DEPEND on the USD → Fabric →
        render-product sync chain to land on the next render.

    Why this design (history):
        v1: Per-frame ClearXformOpOrder() + AddTransformOp() raced the
            renderer (it occasionally caught the half-rebuilt op chain
            mid-frame → completely blank frames).
        v2: Cached the op handle on first call, only .Set() on it
            after — fixed the rebuild-race. But still produced an
            alternating gray-void / pure-black / good-frame pattern
            because USD xform writes don't always reach the GPU pose
            buffer the render product samples for the NEXT render
            pass — there's a USD → Fabric sync step that can lag a
            render. Static mode happens to work because the pose is
            written ONCE before the first render, so by the time any
            render runs the sync has long since completed.
        v3: Skip the USD xform write entirely. Use
            self.camera.set_world_poses_from_view() which goes
            directly to the GPU camera buffer the render product
            reads. Works on Isaac Lab builds where Fabric (usdrt) is
            fully loaded.
        v4 (THIS): Fallback for builds where the tensor API throws
            (e.g. "module 'usdrt' has no attribute 'hierarchy'" — Fabric
            isn't loaded). We TRY the tensor path first, latch the
            outcome on _tensor_pose_works, and on failure fall back to
            the cached USD-xform op PLUS a dual-render in the main sim
            loop on chase capture frames: the first sim.step(render=True)
            after a pose change renders with the stale pose AND completes
            the USD→Fabric sync; the second sim.step(render=True) renders
            with the fresh pose, and that's the frame we capture.

    IMPORTANT usage constraints (do not "fix" these without testing):
      1. The Camera object MUST be constructed BEFORE sim.reset(), so
         its buffers are allocated during scene initialization.
      2. Use sim.step(render=True) on steps where you want a fresh
         render. camera.update(dt) then pulls the render into the data
         tensor, which capture_frame() reads.
      3. set_world_poses_from_view() must be called AFTER sim.reset()
         (so the camera's tensor buffers exist). The first call
         happens inside position() which is called post-reset.
    """

    # Camera offset from robot center (meters), used in 'chase' mode.
    CAM_OFFSET = (-0.22, -0.18, 0.15)

    # Static world-fixed camera pose (used in 'static' mode).
    # Updated 2026-04-30: framing tuned for the actual centipede walk
    # path. The Isaac-v2 baseline gait drifts toward NEGATIVE x at
    # ~5 mm/s, finishing 10 s runs around (-0.05, 0.0, 0.005). The
    # previous target +0.10 along x was the OPPOSITE direction, so
    # the centipede walked AWAY from the camera frame.
    #
    # Geometry of the new framing:
    #   target = (-0.04, 0.0, 0.012) — centred on the mid-walk point,
    #     just above the average terrain peak so the camera looks at
    #     the body, not at the substrate.
    #   eye    = (-0.30, -0.25, 0.18) — 3/4 view: 26 cm behind the
    #     target along x, 25 cm to the side, 17 cm above. Camera-to-
    #     target distance ~ 0.39 m. With our 47° HFoV PinholeCamera,
    #     the visible horizontal extent at the target plane is about
    #     34 cm — comfortably covers a 20-cm walk plus the 10-cm
    #     centipede length plus headroom on either side.
    #   At this distance the centipede occupies roughly 1/3 of the
    #   frame width, which matches the previous "stand_test.mp4"
    #   framing the user was happy with.
    STATIC_EYE    = (-0.30, -0.25, 0.18)
    STATIC_TARGET = (-0.04,  0.0,  0.012)

    # TENSOR-POSE architecture (current — supersedes the cached-op
    # design that left a USD → Fabric sync race in chase mode).
    #   /World/VideoCamera — Camera prim, top-level (no parent Xform).
    #   Constructed via isaaclab.sensors.CameraCfg/Camera so that its
    #   tensor buffers (pos_w, quat_w, GPU pose) are allocated during
    #   sim.reset(). After that, we drive the camera pose by calling
    #   self.camera.set_world_poses_from_view(eyes, targets) which
    #   pushes the pose directly into the GPU buffer the render
    #   product samples on the NEXT sim.step(render=True). USD is
    #   updated as a side-effect but is not on the critical path — so
    #   any USD-vs-Fabric lag can no longer leave the renderer
    #   sampling a stale or unset pose.
    CAM_PATH = "/World/VideoCamera"

    def __init__(self, video_path, width=1280, height=720, fps=30,
                 mode="static"):
        self.video_path = video_path
        self.width = width
        self.height = height
        self.fps = fps
        self.mode = mode                # "chase" | "static"
        self.frames = []
        # USD xform-op cache (used by the legacy USD path). We try the
        # tensor API (set_world_poses_from_view) first; if that fails
        # on this Isaac Lab build (e.g. usdrt/Fabric not loaded), we
        # latch _tensor_pose_works=False so subsequent calls go
        # straight to the USD path WITHOUT re-trying / re-printing.
        # The op handle is acquired once and reused — see _set_world_pose.
        self._xform_op = None
        self._tensor_pose_works = None   # None = untried, True/False = latched

        # Output directory
        dirname = os.path.dirname(video_path)
        if dirname:
            os.makedirs(dirname, exist_ok=True)

        # ── Spawn the Camera (NO OffsetCfg, NO pre-reset xform) ──
        # On this Isaac Lab build OffsetCfg silently fails (it goes
        # through XformPrimView.set_world_poses → usdrt.hierarchy →
        # AttributeError; Camera swallows it and the camera stays at
        # origin). We instead let Camera spawn at default origin,
        # and AFTER sim.reset() we write a USD TransformOp directly.
        # The TransformOp write is what worked on v9 chase video.
        from isaaclab.sensors import CameraCfg, Camera
        cam_cfg = CameraCfg(
            prim_path=self.CAM_PATH,
            update_period=0.0,           # update every time we ask
            height=height,
            width=width,
            data_types=["rgb"],
            spawn=sim_utils.PinholeCameraCfg(
                # 24mm lens on a 20.955mm horizontal aperture → ~47° HFoV.
                focal_length=24.0,
                focus_distance=400.0,
                horizontal_aperture=20.955,
                # CRITICAL: a tight near plane like 0.001 destroys
                # depth-buffer precision. 0.05 = 5 cm.
                clipping_range=(0.05, 100.0),
            ),
        )
        self.camera = Camera(cfg=cam_cfg)

        print(f"[VideoRecorder] tensor-pose camera "
              f"{width}x{height} @ {fps}fps, mode={mode}")
        print(f"  cam prim: {self.CAM_PATH}")
        if mode == "chase":
            print(f"  chase offset: {self.CAM_OFFSET}")
        else:
            print(f"  static eye/target: {self.STATIC_EYE} / {self.STATIC_TARGET}")

    @staticmethod
    def _lookat_quaternion(eye, target):
        """Compute the (w,x,y,z) quaternion (OpenGL camera convention)
        of a camera at `eye` looking at `target` with world-up = +Z.

        OpenGL/USD camera convention: cam looks down its local -Z, +X
        is right, +Y is up. Returned quaternion rotates camera-local
        axes to world axes. Pass `convention="opengl"` to
        Camera.OffsetCfg / set_world_poses so it isn't re-rotated.
        """
        import math as _math
        ex, ey, ez = float(eye[0]),    float(eye[1]),    float(eye[2])
        tx, ty, tz = float(target[0]), float(target[1]), float(target[2])
        fx, fy, fz = tx - ex, ty - ey, tz - ez
        n = max(_math.sqrt(fx*fx + fy*fy + fz*fz), 1e-12)
        fx, fy, fz = fx/n, fy/n, fz/n
        # right = fwd × up   where up = (0,0,1)
        rx, ry, rz = fy*1.0 - fz*0.0, fz*0.0 - fx*1.0, fx*0.0 - fy*0.0
        n = max(_math.sqrt(rx*rx + ry*ry + rz*rz), 1e-12)
        rx, ry, rz = rx/n, ry/n, rz/n
        # cam_up = right × fwd
        ux = ry*fz - rz*fy
        uy = rz*fx - rx*fz
        uz = rx*fy - ry*fx
        # Rotation matrix columns: right, cam_up, -fwd
        r00, r01, r02 = rx, ux, -fx
        r10, r11, r12 = ry, uy, -fy
        r20, r21, r22 = rz, uz, -fz
        # Shepperd's branchless rotation→quaternion
        tr = r00 + r11 + r22
        if tr > 0:
            s = _math.sqrt(tr + 1.0) * 2.0
            qw = 0.25 * s
            qx = (r21 - r12) / s
            qy = (r02 - r20) / s
            qz = (r10 - r01) / s
        elif r00 > r11 and r00 > r22:
            s = _math.sqrt(1.0 + r00 - r11 - r22) * 2.0
            qw = (r21 - r12) / s
            qx = 0.25 * s
            qy = (r01 + r10) / s
            qz = (r02 + r20) / s
        elif r11 > r22:
            s = _math.sqrt(1.0 + r11 - r00 - r22) * 2.0
            qw = (r02 - r20) / s
            qx = (r01 + r10) / s
            qy = 0.25 * s
            qz = (r12 + r21) / s
        else:
            s = _math.sqrt(1.0 + r22 - r00 - r11) * 2.0
            qw = (r10 - r01) / s
            qx = (r02 + r20) / s
            qy = (r12 + r21) / s
            qz = 0.25 * s
        return qw, qx, qy, qz

    # _write_usd_xform_pre_reset removed: replaced by passing
    # CameraCfg.OffsetCfg(pos, rot, convention) to the CameraCfg in
    # __init__. That is the canonical Isaac Lab way to position a
    # camera at spawn — Camera._initialize_impl writes the pose into
    # Fabric for us during sim.reset(), so we don't have to fight USD
    # xform-op semantics. Manual USD xform writes were silently
    # overwritten by Camera's own initialization on this build.

    def _set_world_pose(self, eye, target):
        """Push the camera's world pose (eye + look-at target) directly
        to the GPU camera buffer via Isaac Lab's tensor API.

        Why not write the USD xform op?
            UsdGeom.XformOp.Set() is visible to USD queries
            immediately, but only propagates to Fabric (and through
            Fabric to the GPU pose buffer the render product samples)
            on certain sim ticks. In chase mode that intermittent lag
            produced the alternating-frame symptom: a render runs
            BEFORE the new pose has reached the GPU buffer, so the
            renderer samples whatever was last there — sometimes a
            stale pose pointing at empty sky (uniform gray), sometimes
            an unset / zeroed pose that produces a fully black frame.

            self.camera.set_world_poses_from_view() instead computes
            the look-at orientation in torch, builds (pos, quat) on
            the camera's own device, and writes them to the GPU
            tensor the next sim.step(render=True) will read. No USD
            sync involved on the critical path → no race.

        Coordinate convention: set_world_poses_from_view internally
        produces an OpenGL-camera-convention pose (camera looks down
        its local -Z, +X right, +Y up) which matches our PinholeCamera
        spawn. We pass world-space eye and target; the method handles
        the rest.

        Falls back to USD xform writes if the tensor API isn't
        available (older Isaac Lab versions). The fallback path will
        still hit the alternating-frame race in chase mode but is the
        best we can do on those versions.
        """
        eye_xyz    = (float(eye[0]),    float(eye[1]),    float(eye[2]))
        target_xyz = (float(target[0]), float(target[1]), float(target[2]))

        # ── Tensor pose API (preferred — writes to the camera's
        #    Fabric pose buffer, which is what the render product
        #    actually samples on each sim.step(render=True)). We try
        #    set_world_poses with a HAND-COMPUTED quaternion rather
        #    than set_world_poses_from_view because, on this Isaac
        #    Lab build, the look-at math inside _from_view dies on
        #    "module 'usdrt' has no attribute 'hierarchy'" (Fabric
        #    isn't fully loaded). set_world_poses skips that math
        #    and might survive the same usdrt limitation.
        #
        #    self._tensor_pose_works is latched (None → True/False)
        #    after the first attempt so we never re-throw / re-print
        #    in the per-frame call path.
        if self._tensor_pose_works is not False:
            try:
                import torch
                import numpy as _np
                # Resolve camera device.
                try:
                    cam_device = self.camera.device
                except AttributeError:
                    cam_device = getattr(self.camera, "_device", "cuda")
                # Look-at orientation, world up = +Z. The result is in
                # USD/OpenGL camera convention (camera looks down its
                # local -Z, +X right, +Y up) — we pass convention="opengl"
                # to set_world_poses so it doesn't re-rotate it.
                eye_np = _np.asarray(eye_xyz,    dtype=_np.float64)
                tgt_np = _np.asarray(target_xyz, dtype=_np.float64)
                fwd = tgt_np - eye_np
                fwd /= max(_np.linalg.norm(fwd), 1e-12)
                up_world = _np.array([0.0, 0.0, 1.0])
                right = _np.cross(fwd, up_world)
                right /= max(_np.linalg.norm(right), 1e-12)
                cam_up = _np.cross(right, fwd)
                # Camera basis in world coords (columns of R):
                #   col 0 = right     (cam +X in world)
                #   col 1 = cam_up    (cam +Y in world)
                #   col 2 = -fwd      (cam +Z in world; cam looks down -Z)
                R = _np.column_stack([right, cam_up, -fwd])
                # Rotation matrix → (w,x,y,z) quaternion. Standard
                # Shepperd/branchless conversion.
                tr = R[0,0] + R[1,1] + R[2,2]
                if tr > 0:
                    s = _np.sqrt(tr + 1.0) * 2
                    qw = 0.25 * s
                    qx = (R[2,1] - R[1,2]) / s
                    qy = (R[0,2] - R[2,0]) / s
                    qz = (R[1,0] - R[0,1]) / s
                elif R[0,0] > R[1,1] and R[0,0] > R[2,2]:
                    s = _np.sqrt(1.0 + R[0,0] - R[1,1] - R[2,2]) * 2
                    qw = (R[2,1] - R[1,2]) / s
                    qx = 0.25 * s
                    qy = (R[0,1] + R[1,0]) / s
                    qz = (R[0,2] + R[2,0]) / s
                elif R[1,1] > R[2,2]:
                    s = _np.sqrt(1.0 + R[1,1] - R[0,0] - R[2,2]) * 2
                    qw = (R[0,2] - R[2,0]) / s
                    qx = (R[0,1] + R[1,0]) / s
                    qy = 0.25 * s
                    qz = (R[1,2] + R[2,1]) / s
                else:
                    s = _np.sqrt(1.0 + R[2,2] - R[0,0] - R[1,1]) * 2
                    qw = (R[1,0] - R[0,1]) / s
                    qx = (R[0,2] + R[2,0]) / s
                    qy = (R[1,2] + R[2,1]) / s
                    qz = 0.25 * s
                pos_t = torch.tensor([eye_xyz], dtype=torch.float32,
                                     device=cam_device)
                quat_t = torch.tensor([[qw, qx, qy, qz]],
                                      dtype=torch.float32,
                                      device=cam_device)
                self.camera.set_world_poses(positions=pos_t,
                                             orientations=quat_t,
                                             convention="opengl")
                if self._tensor_pose_works is None:
                    self._tensor_pose_works = True
                    print("[VideoRecorder] tensor pose API works — "
                          "using Camera.set_world_poses (Fabric write).",
                          flush=True)
                return
            except Exception as e:
                # Latch the failure so we don't re-try / re-print
                # hundreds of times per video.
                self._tensor_pose_works = False
                print(f"[VideoRecorder] tensor pose API unavailable "
                      f"({type(e).__name__}: {e}) — falling back to "
                      f"USD xform write. THIS WILL PRODUCE FLICKERING "
                      f"VIDEO IN CHASE MODE because USD writes don't "
                      f"reach Fabric reliably on this build. Use "
                      f"--camera-mode static for a clean video. "
                      f"This message prints ONCE.", flush=True)

        # ── Post-reset USD TransformOp write (the v9 working path) ──
        # On this Isaac Lab build:
        #   1. set_world_poses* tensor APIs throw usdrt.hierarchy
        #      AttributeError → can't push pose via Fabric
        #   2. CameraCfg.OffsetCfg silently fails for the same reason
        #      (it uses set_world_poses internally during reset)
        #   3. The renderer DOES respond to a USD TransformOp written
        #      directly to the camera prim AFTER sim.reset(). v9 chase
        #      videos with visible centipede prove this empirically.
        # So we Clear+AddTransformOp+Set per call. This breaks the
        # canonical translate/orient/scale structure that XformPrimView
        # validated at sim.reset() time, but XformPrimView's validation
        # only runs ONCE during reset, so post-reset op-replacement is
        # safe.
        import omni.usd
        from pxr import UsdGeom, Gf
        stage = omni.usd.get_context().get_stage()
        cam_prim = stage.GetPrimAtPath(self.CAM_PATH)
        if not cam_prim.IsValid():
            print(f"[VideoRecorder] WARNING: {self.CAM_PATH} not in stage; "
                  f"cannot set camera pose.", flush=True)
            return
        eye_v = Gf.Vec3d(*eye_xyz)
        tgt_v = Gf.Vec3d(*target_xyz)
        up    = Gf.Vec3d(0, 0, 1)
        fwd    = (tgt_v - eye_v).GetNormalized()
        right  = (fwd ^ up).GetNormalized()
        cam_up = (right ^ fwd).GetNormalized()
        m = Gf.Matrix4d()
        m.SetRow(0, Gf.Vec4d(right[0],  right[1],  right[2],  0))
        m.SetRow(1, Gf.Vec4d(cam_up[0], cam_up[1], cam_up[2], 0))
        m.SetRow(2, Gf.Vec4d(-fwd[0],   -fwd[1],   -fwd[2],   0))
        m.SetRow(3, Gf.Vec4d(eye_v[0],  eye_v[1],  eye_v[2],  1))
        if self._xform_op is None:
            xformable = UsdGeom.Xformable(cam_prim)
            existing = xformable.GetOrderedXformOps()
            transform_op = None
            for op in existing:
                if op.GetOpType() == UsdGeom.XformOp.TypeTransform:
                    transform_op = op
                    break
            if transform_op is None:
                xformable.ClearXformOpOrder()
                transform_op = xformable.AddTransformOp()
            self._xform_op = transform_op
        self._xform_op.Set(m)

    def position(self, target_pos=None):
        """Place the camera AFTER sim.reset(). Static mode uses fixed
        eye/target. Chase mode places the camera at robot_pos + offset
        looking at robot_pos."""
        if self.mode == "static":
            eye = self.STATIC_EYE
            tgt = self.STATIC_TARGET
        else:
            if target_pos is None:
                target_pos = (0.0, 0.0, 0.02)
            tgt = (float(target_pos[0]),
                   float(target_pos[1]),
                   float(target_pos[2]))
            eye = (tgt[0] + self.CAM_OFFSET[0],
                   tgt[1] + self.CAM_OFFSET[1],
                   tgt[2] + self.CAM_OFFSET[2])
        self._set_world_pose(eye, tgt)

    def update_camera(self, target_pos):
        """Per-frame chase update: rebuild eye+target from the current
        robot position and push the new pose to the GPU camera buffer
        via Camera.set_world_poses (Fabric write — see _set_world_pose
        for why the USD path is bypassed).

        ── NaN / extreme-value guard ──
        If the controller is unstable (e.g. MuJoCo-tuned soft gains
        running on PhysX rough terrain), the centipede can explode
        and root_pos_w becomes NaN / inf / a huge number. Passing
        that into set_world_poses puts garbage in the GPU camera
        buffer and EVERY subsequent frame renders black. That used
        to look identical to a render-pipeline bug, which sent us
        chasing the wrong fix (see NOTES_RENDERING.md).

        We now reject any target_pos that is NaN / inf or beyond
        ±5 m of world origin (sane robot is within ±0.5 m). On
        rejection we keep the camera at its last valid pose and log
        ONCE so the operator knows the controller blew up rather
        than the renderer.
        """
        if self.mode != "chase":
            return

        tgt_x, tgt_y, tgt_z = float(target_pos[0]), float(target_pos[1]), float(target_pos[2])
        bad = (not np.all(np.isfinite([tgt_x, tgt_y, tgt_z]))
               or max(abs(tgt_x), abs(tgt_y), abs(tgt_z)) > 5.0)
        if bad:
            if not getattr(self, "_chase_blowup_logged", False):
                print(f"[VideoRecorder] CHASE TARGET INVALID — "
                      f"target_pos=({tgt_x}, {tgt_y}, {tgt_z}). "
                      f"Robot likely exploded (controller unstable). "
                      f"Freezing camera at last valid pose. "
                      f"This message prints ONCE. The black frames "
                      f"you're about to see are NOT a render bug — "
                      f"check controller stability "
                      f"(rollback to Isaac-v2 gains if you just "
                      f"changed the YAML).", flush=True)
                self._chase_blowup_logged = True
            return  # keep last good pose

        tgt = (tgt_x, tgt_y, tgt_z)
        eye = (tgt[0] + self.CAM_OFFSET[0],
               tgt[1] + self.CAM_OFFSET[1],
               tgt[2] + self.CAM_OFFSET[2])
        self._set_world_pose(eye, tgt)

    def capture_frame(self):
        """Read the latest rendered RGB frame and append it to the buffer.

        Assumes the caller has just done sim.step(render=True) and
        self.camera.update(dt) so camera.data.output["rgb"] is fresh.

        Per the Isaac Lab Camera source, data.output["rgb"] is a torch
        tensor of shape (num_cameras, H, W, 3) and dtype torch.uint8.
        """
        rgb = self.camera.data.output.get("rgb", None)
        if rgb is None:
            if len(self.frames) < 3:
                print("[VideoRecorder] capture_frame: rgb is None (first calls)")
            return
        arr = rgb[0].detach().cpu().numpy()

        # Tiny diagnostic for the first frame only — confirms the
        # renderer is producing real content. Removed the per-frame
        # USD-vs-GPU pose probe and the 3-frame debug PNG dump; both
        # cost wall-clock time and were the historical cause of laggy
        # video for slow-physics gaits (their cost was a substantial
        # fraction of the per-frame budget on the first few captures).
        n = len(self.frames)
        if n == 0:
            try:
                print(f"[VideoRecorder] first capture: shape={arr.shape} "
                      f"dtype={arr.dtype} "
                      f"min={int(arr.min())} max={int(arr.max())} "
                      f"mean={float(arr.mean()):.1f}",
                      flush=True)
            except Exception:
                pass

        # Convert to uint8 RGB. Per the docs, RGB output is already uint8.
        if arr.dtype != np.uint8:
            if arr.max() <= 1.5:           # float in [0,1]
                arr = np.clip(arr, 0.0, 1.0)
                arr = (arr * 255.0).astype(np.uint8)
            else:
                arr = np.clip(arr, 0, 255).astype(np.uint8)
        if arr.ndim == 3 and arr.shape[2] == 4:
            arr = arr[:, :, :3]
        if arr.ndim != 3 or arr.size == 0:
            return

        # ── Bad-frame race guard (BLACK + UNIFORM-SKY) ──
        # RESTORED 2026-05-04 after a brief refactor that copied
        # render_top_trials.py's simpler `mean<3 only` guard. That
        # refactor produced completely-black video on this build —
        # consistent with NOTES_RENDERING §0's explicit warning:
        # the `std<5` test is an "accidental kludge" that filters out
        # camera-at-origin floor/dome frames (low std) and lets
        # centipede-close-up frames (high std) through. Without it,
        # test_walk's chase video is unwatchable.
        #
        # Two distinct failure modes share the same fix (replace with
        # previous good frame). Both arise because Isaac Sim's
        # Replicator annotator `get_data()` does NOT block on the GPU
        # render — it returns whatever is currently in its output
        # buffer.
        #
        #   FAILURE MODE A — pure black (mean < 3):
        #     Annotator's output buffer hasn't been written yet (the
        #     GPU render didn't finish before camera.update(dt)).
        #     Most common on rough terrain with 32k-tri heightfield BVH.
        #
        #   FAILURE MODE B — uniform sky/floor (std < 5):
        #     The renderer falls behind on consecutive sim.step(
        #     render=True) calls. The annotator keeps returning the
        #     SAME frame from its cache for many captures in a row.
        #     When that cached frame happens to be the camera looking
        #     at empty sky/floor, std is ~1-5, the video gets a long
        #     uniform-color hold. Diagnostic: ffmpeg-extract +
        #     numpy mean/std shows MULTIPLE consecutive captures with
        #     EXACTLY the same mean/std to one decimal place.
        #
        # Both detection rules are independent and combined with OR.
        # This is a presentation-layer fix; the underlying USD/Fabric
        # camera-pose desync is a build-level issue we cannot fix
        # without an Isaac Lab upgrade. See NOTES_RENDERING §0 for
        # the full mental model.
        mean_v = float(arr.mean())
        std_v  = float(arr.std())
        is_black   = mean_v < 3.0
        is_uniform = std_v  < 5.0
        is_bad     = is_black or is_uniform
        if is_bad and len(self.frames) > 0:
            if not getattr(self, "_bad_frame_logged", False):
                kind = "BLACK" if is_black else "UNIFORM-SKY"
                print(f"[VideoRecorder] frame {n} is {kind} "
                      f"(mean={mean_v:.1f}, std={std_v:.1f}). "
                      f"Replacing with previous good frame. "
                      f"(Cause: Replicator annotator returned "
                      f"un-finalised or stale buffer. This message "
                      f"prints ONCE.)",
                      flush=True)
                self._bad_frame_logged = True
            arr = self.frames[-1].copy()
            if is_black:
                self._black_frames_replaced = (
                    getattr(self, "_black_frames_replaced", 0) + 1)
            else:
                self._uniform_frames_replaced = (
                    getattr(self, "_uniform_frames_replaced", 0) + 1)
        elif is_bad:
            # First frame is bad AND no previous to copy.
            # Skip — better to start the video on the first good
            # frame than to lead with a bad flash. (If EVERY frame is
            # bad — which happens for slow-physics gaits like trial
            # #47 — the video will be empty. Use render_top_trials.py
            # for those instead; it has a different render-loop
            # overhead profile that succeeds where test_walk fails.)
            if not getattr(self, "_bad_frame_logged", False):
                kind = "BLACK" if is_black else "UNIFORM-SKY"
                print(f"[VideoRecorder] frame {n} is {kind} "
                      f"(mean={mean_v:.1f}, std={std_v:.1f}) with "
                      f"no previous frame to copy — skipping.",
                      flush=True)
                self._bad_frame_logged = True
            return

        self.frames.append(arr)

    def save(self):
        """Write all frames to MP4."""
        if not self.frames:
            print("[VideoRecorder] No frames captured — skipping video save.")
            return

        n_black   = getattr(self, "_black_frames_replaced",   0)
        n_uniform = getattr(self, "_uniform_frames_replaced", 0)
        n_total   = len(self.frames)
        if n_black + n_uniform > 0:
            pct = 100.0 * (n_black + n_uniform) / max(n_total, 1)
            print(f"[VideoRecorder] bad-frame guard summary: "
                  f"replaced {n_black + n_uniform}/{n_total} "
                  f"({pct:.1f}%) — black={n_black}, "
                  f"uniform-sky={n_uniform}. black=GPU race, "
                  f"uniform-sky=renderer falling behind capture rate.",
                  flush=True)
        print(f"[VideoRecorder] Writing {len(self.frames)} frames to {self.video_path}...")
        try:
            import cv2
            h, w = self.frames[0].shape[:2]
            fourcc = cv2.VideoWriter_fourcc(*'mp4v')
            writer = cv2.VideoWriter(self.video_path, fourcc, self.fps, (w, h))
            for frame in self.frames:
                writer.write(cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))
            writer.release()
            print(f"[VideoRecorder] Saved → {self.video_path}")
        except ImportError:
            # Fallback to imageio
            try:
                import imageio
                imageio.mimwrite(self.video_path, self.frames, fps=self.fps)
                print(f"[VideoRecorder] Saved → {self.video_path} (imageio)")
            except ImportError:
                # Last resort: save frames as images
                frame_dir = self.video_path.replace('.mp4', '_frames')
                os.makedirs(frame_dir, exist_ok=True)
                from PIL import Image
                for i, f in enumerate(self.frames):
                    Image.fromarray(f).save(os.path.join(frame_dir, f"frame_{i:06d}.png"))
                print(f"[VideoRecorder] Saved {len(self.frames)} frames to {frame_dir}/")
                print(f"  Convert with: ffmpeg -r {self.fps} -i {frame_dir}/frame_%06d.png -c:v libx264 {self.video_path}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    # Read timestep from config YAML so you only change it in one place
    config_path = os.path.join(BASE_DIR, "configs", "farms_controller.yaml")
    if not os.path.isfile(config_path):
        config_path = os.path.join(BASE_DIR, "..", "Centipede_MUJOCO-main",
                                   "configs", "farms_controller.yaml")
    import yaml
    with open(config_path, "r", encoding="utf-8") as f:
        _cfg = yaml.safe_load(f)
    _dt = float(_cfg.get("simulation", {}).get("timestep", 0.004))

    sim_cfg = SimulationCfg(dt=_dt)
    sim = SimulationContext(sim_cfg)
    sim.set_camera_view(eye=[0.5, 0.5, 0.3], target=[0.0, 0.0, 0.0])

    # ── Lighting ──
    # Isaac Sim scenes are pitch black without explicit lights.
    # Previous values (dome=1000, distant=3000) blew out the ground to
    # pure white and made the dark robot body invisible against it.
    # New values aim for a studio-product-shot look: soft ambient fill
    # plus a single key light with visible shadow direction.
    from pxr import UsdGeom, UsdLux, Gf, Sdf
    stage = sim.stage

    # Dome light: gentle ambient fill, slightly cool tint.
    dome = UsdLux.DomeLight.Define(stage, "/World/DomeLight")
    dome.GetIntensityAttr().Set(300.0)
    dome.GetColorAttr().Set(Gf.Vec3f(0.95, 0.97, 1.0))

    # Distant (sun) light: single directional key for shadows.
    dist_light = UsdLux.DistantLight.Define(stage, "/World/DistantLight")
    dist_light.GetIntensityAttr().Set(800.0)
    dist_light.GetAngleAttr().Set(0.53)
    dist_light.GetColorAttr().Set(Gf.Vec3f(1.0, 0.98, 0.92))
    xf = UsdGeom.Xformable(dist_light.GetPrim())
    xf.AddRotateXYZOp().Set(Gf.Vec3f(-45.0, 30.0, 0.0))

    # ── Ground / terrain ─────────────────────────────────────────────
    # Two modes:
    #   --terrain flat (default) → thin cube slab at z=0, 100×100m.
    #   --terrain rough          → single-wavelength heightmap mesh
    #                              generated by scripts/optimization/
    #                              terrain.py — same API the Bayesian
    #                              optimizer uses, so a walk test can
    #                              be performed on the EXACT terrain
    #                              the gains are tuned for.
    from pxr import UsdPhysics, UsdShade
    ground_path = "/World/GroundPlane"
    UsdGeom.Xform.Define(stage, ground_path)

    # Physics material is shared between flat and rough — friction
    # matches MuJoCo XML (1.6 / 1.6 / 0).
    phys_mat_path = "/World/PhysicsMaterials/GroundMaterial"
    phys_mat = UsdShade.Material.Define(stage, phys_mat_path)
    phys_mat_api = UsdPhysics.MaterialAPI.Apply(phys_mat.GetPrim())
    phys_mat_api.CreateStaticFrictionAttr(1.6)
    phys_mat_api.CreateDynamicFrictionAttr(1.6)
    phys_mat_api.CreateRestitutionAttr(0.0)

    # Visual material — dark cool gray so the near-black robot reads.
    vis_mat_path = ground_path + "/VisualMaterial"
    vis_mat = UsdShade.Material.Define(stage, vis_mat_path)
    shader = UsdShade.Shader.Define(stage, vis_mat_path + "/Shader")
    shader.CreateIdAttr("UsdPreviewSurface")
    shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(
        Gf.Vec3f(0.18, 0.20, 0.24))
    shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.95)
    shader.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(0.0)
    vis_mat.CreateSurfaceOutput().ConnectToSource(
        shader.ConnectableAPI(), "surface")

    # Guard: --terrain arena is recognised in argparse for forward
    # compatibility (the optimizer's --arena mode dumps an
    # arena_blocks.json that this script does NOT yet know how to
    # rebuild). Refuse cleanly so we never silently fall through to
    # the rough branch with stale single-wavelength defaults.
    if args.terrain == "arena":
        print("ERROR: --terrain arena is not supported by test_walk.py "
              "yet.\n"
              "       For arena-faithful replays use:\n"
              "         python scripts/optimization/render_top_trials.py "
              "--arena-blocks-json <PATH>\n"
              "       (once render_top_trials gains --arena-blocks-json "
              "support).", flush=True)
        sim_app.close()
        sys.exit(2)

    if args.terrain == "flat":
        # Thin cube slab. Default Cube is 2m on a side; we scale x,y to
        # a 100m × 100m floor, keep z thin (10cm), and translate so the
        # TOP surface is exactly at z=0 (and the bottom at z=-0.1).
        slab_path = ground_path + "/Slab"
        slab = UsdGeom.Cube.Define(stage, slab_path)
        slab.GetSizeAttr().Set(1.0)
        slab_xform = UsdGeom.Xformable(slab)
        slab_xform.ClearXformOpOrder()
        slab_xform.AddTranslateOp().Set(Gf.Vec3d(0.0, 0.0, -0.05))
        slab_xform.AddScaleOp().Set(Gf.Vec3f(100.0, 100.0, 0.1))

        UsdPhysics.CollisionAPI.Apply(slab.GetPrim())
        binding_api = UsdShade.MaterialBindingAPI.Apply(slab.GetPrim())
        binding_api.Bind(phys_mat,
                         bindingStrength=UsdShade.Tokens.weakerThanDescendants,
                         materialPurpose="physics")
        UsdShade.MaterialBindingAPI(slab.GetPrim()).Bind(vis_mat)

        try:
            local_to_world = UsdGeom.Xformable(slab.GetPrim()) \
                .ComputeLocalToWorldTransform(0)
            top_world = local_to_world.Transform(Gf.Vec3d(0, 0, 0.5))
            bot_world = local_to_world.Transform(Gf.Vec3d(0, 0, -0.5))
            print(f"[Ground] flat slab world: top z={top_world[2]:+.4f}  "
                  f"bottom z={bot_world[2]:+.4f}", flush=True)
        except Exception as e:
            print(f"[Ground] could not compute slab transform: {e}",
                  flush=True)
    else:  # rough
        # Generate the heightmap and bake it as a USD triangle mesh
        # with PhysX collision. We apply MuJoCo's PNG quantisation +
        # z-shift inside build_terrain_mesh (mujoco_compat=True is the
        # default) so the physical surface PhysX collides against is
        # IDENTICAL to MuJoCo's <hfield> world heights at every pixel.
        sys.path.insert(0, os.path.join(BASE_DIR, "scripts"))
        from optimization.terrain import (
            generate_single_wavelength_heightmap,
            build_terrain_mesh,
            to_mujoco_terrain,
            mujoco_z_max,
            mujoco_spawn_z,
            MUJOCO_Z_BOTTOM_SKIRT,
        )
        wl  = float(args.terrain_wavelength)
        amp = float(args.terrain_amplitude)
        ws  = float(args.terrain_world_size)
        seed = int(args.terrain_seed)
        print(f"[Ground] rough heightmap: wavelength={wl*1000:.1f}mm, "
              f"peak_amplitude={amp*1000:.1f}mm, world_size={ws:.2f}m, "
              f"seed={seed}", flush=True)
        h_m, rms_m, peak_m = generate_single_wavelength_heightmap(
            wavelength_m=wl, amplitude_m=amp, seed=seed,
            image_size=1024, world_size=ws,
        )
        z_max = mujoco_z_max(peak_m)
        print(f"[Ground] heightmap stats (float, mean-centred): "
              f"rms={rms_m*1000:.2f}mm  peak={peak_m*1000:.2f}mm",
              flush=True)
        print(f"[Ground] MuJoCo physical model: z_max={z_max*1000:.2f}mm "
              f"(= max(2*peak, 5mm)), terrain world z ∈ [0, "
              f"{z_max*1000:.2f}mm], skirt {MUJOCO_Z_BOTTOM_SKIRT*1000:.0f}mm "
              f"below.", flush=True)

        mesh_path = ground_path + "/RoughMesh"
        # mesh_resolution=1024 = same as MuJoCo's hfield row/col count.
        # mujoco_compat=True (default) shifts heights to [0, z_max] and
        # quantises through the uint8 PNG path; pass False if you want
        # the smoother float-precision mesh instead.
        mesh_prim = build_terrain_mesh(
            stage, mesh_path, h_m,
            world_size=ws,
            mesh_resolution=1024,
            mujoco_compat=True,
        )
        # Bind physics + visual materials.
        binding_api = UsdShade.MaterialBindingAPI.Apply(mesh_prim.GetPrim())
        binding_api.Bind(phys_mat,
                         bindingStrength=UsdShade.Tokens.weakerThanDescendants,
                         materialPurpose="physics")
        UsdShade.MaterialBindingAPI(mesh_prim.GetPrim()).Bind(vis_mat)

        # Big flat slab UNDERNEATH the heightmap so the robot doesn't
        # fall into the void if it walks past the 1m terrain patch.
        # In MuJoCo-compat mode the rough surface spans world z ∈
        # [0, z_max], so the under-floor top must sit at z = -skirt
        # (1 mm below the world origin) to mirror MuJoCo's hfield skirt.
        floor_path = ground_path + "/UnderFloor"
        floor = UsdGeom.Cube.Define(stage, floor_path)
        floor.GetSizeAttr().Set(1.0)
        floor_xform = UsdGeom.Xformable(floor)
        floor_xform.ClearXformOpOrder()
        z_top   = -float(MUJOCO_Z_BOTTOM_SKIRT)   # mirror MuJoCo's skirt
        z_thick = 0.10
        z_center = z_top - z_thick / 2.0
        floor_xform.AddTranslateOp().Set(Gf.Vec3d(0.0, 0.0, z_center))
        floor_xform.AddScaleOp().Set(Gf.Vec3f(100.0, 100.0, z_thick))
        UsdPhysics.CollisionAPI.Apply(floor.GetPrim())
        binding_floor = UsdShade.MaterialBindingAPI.Apply(floor.GetPrim())
        binding_floor.Bind(phys_mat,
                           bindingStrength=UsdShade.Tokens.weakerThanDescendants,
                           materialPurpose="physics")
        UsdShade.MaterialBindingAPI(floor.GetPrim()).Bind(vis_mat)
        # Compute MuJoCo-equivalent spawn z so the centipede lands above
        # the highest point under its body (max within ±7.5 cm of the
        # centre), with the same 15 mm clearance MuJoCo uses.
        mujoco_spawn_z_value = mujoco_spawn_z(h_m, world_size=ws)
        # Stash so the centipede spawn translation can pick it up below.
        args._rough_spawn_z = mujoco_spawn_z_value
        print(f"[Ground] under-floor top z={z_top:+.4f}m, "
              f"spawn_z={mujoco_spawn_z_value*1000:.2f}mm "
              f"(= max(terrain) within ±7.5cm + 15mm clearance, "
              f"MuJoCo recipe)", flush=True)

    # ── Spawn centipede USD ──
    usd_path = os.path.join(BASE_DIR, "assets", "centipede.usd")
    if not os.path.isfile(usd_path):
        print(f"ERROR: USD not found: {usd_path}")
        print(f"Run convert_mjcf.py first.")
        sim_app.close()
        sys.exit(1)

    # Spawn z: in flat mode the centipede just spawns 2 cm above the
    # slab. In rough mode we use MuJoCo's spawn_z_from_png recipe so
    # the centipede lands the same way MuJoCo does — above the highest
    # peak directly under its body, with 15 mm clearance.
    if args.terrain == "rough" and hasattr(args, "_rough_spawn_z"):
        spawn_z = float(args._rough_spawn_z)
    else:
        spawn_z = 0.02
    spawn_cfg = sim_utils.UsdFileCfg(usd_path=usd_path)
    spawn_cfg.func("/World/Centipede", spawn_cfg,
                   translation=(0.0, 0.0, spawn_z))
    print(f"[Centipede] spawned at translation=(0, 0, {spawn_z*1000:.2f}mm)",
          flush=True)

    # Suppress the MJCF importer's worldBody subtree.
    #
    # The centipede MJCF (centipede.xml) defines a <geom name="floor">
    # inside <worldbody>. When the MJCF importer converts that to USD,
    # it creates /World/Centipede/worldBody/floor/collisions/CollisionPlane
    # — a real PhysX collision plane that we DON'T want, because we
    # have our own ground plane at /World/GroundPlane/Slab.
    #
    # CRITICAL: stage.RemovePrim() does NOT work here. The worldBody
    # prim is defined inside a *referenced* USD layer (centipede_base.usd
    # / centipede_physics.usd), so RemovePrim only removes a local
    # override and the referenced prim composes back in. The Stage
    # panel in Isaac Sim still shows it after "removal".
    # The correct API is prim.SetActive(False), which deactivates the
    # prim (and its entire subtree) in the composed stage without
    # touching the reference.
    world_body_prim = stage.GetPrimAtPath("/World/Centipede/worldBody")
    if world_body_prim.IsValid():
        world_body_prim.SetActive(False)
        print("Deactivated /World/Centipede/worldBody (MJCF floor + sensors)",
              flush=True)
    else:
        # Fall-through: search for any CollisionPlane under the centipede
        # in case the path differs in this Isaac Lab version.
        for prim in stage.Traverse():
            path = prim.GetPath().pathString
            if path.startswith("/World/Centipede/") and \
               "CollisionPlane" in path:
                prim.SetActive(False)
                print(f"Deactivated stray collision plane: {path}",
                      flush=True)

    # ── Create Articulation ──
    # Three actuator groups matching MuJoCo XML joint properties:
    #   active:      effort-mode (stiffness=0, damping=0) — our controller sets torques
    #   leg_roll:    passive (stiffness=0.01, damping=0.005 from XML)
    #   foot:        passive (damping=0.006 from XML)
    robot_cfg = ArticulationCfg(
        prim_path="/World/Centipede/link_body_0",
        spawn=None,
        init_state=ArticulationCfg.InitialStateCfg(
            pos=(0.0, 0.0, 0.02),
        ),
        actuators={
            "active_joints": ImplicitActuatorCfg(
                # Simplified MJCF: keeps body-pitch joints (added back
                # for vertical compliance), removes body-roll and
                # leg-roll joints (which produced multi-DOF compounds
                # PhysX couldn't solve). See scripts/simplify_mjcf.py.
                joint_names_expr=[
                    "joint_body_.*",
                    "joint_pitch_body_.*",
                    "joint_leg_.*",
                ],
                effort_limit=10.0,
                velocity_limit=100.0,
                stiffness=0.0,
                damping=0.0,
            ),
            "foot_passive": ImplicitActuatorCfg(
                joint_names_expr=["joint_foot_.*"],
                effort_limit=1.0,
                velocity_limit=100.0,
                stiffness=0.0,
                damping=0.006,
            ),
        },
    )
    robot = Articulation(robot_cfg)

    # ── Video recorder MUST be created before sim.reset() so the
    #     isaaclab Camera sensor's render_product is allocated during
    #     scene initialization.
    recorder = None
    if args.video:
        video_path = args.video
        if not os.path.isabs(video_path):
            video_path = os.path.join(BASE_DIR, video_path)
        recorder = VideoRecorder(video_path, fps=args.video_fps,
                                 mode=args.camera_mode)

    sim.reset()
    robot.reset()

    # ── DIAGNOSTIC: enumerate every prim with PhysX collision so we
    #     can confirm there's no second "invisible" collision plane
    #     introduced by the rendering experience or by some default
    #     scene asset besides our cube slab.
    print("\n[DIAG] All collision-bearing prims after sim.reset():",
          flush=True)
    from pxr import UsdPhysics as _UsdPhysics
    coll_count = 0
    for prim in stage.Traverse():
        if prim.HasAPI(_UsdPhysics.CollisionAPI):
            coll_count += 1
            path = prim.GetPath().pathString
            ptype = prim.GetTypeName()
            try:
                xf = UsdGeom.Xformable(prim)
                m = xf.ComputeLocalToWorldTransform(0)
                pos = m.ExtractTranslation()
                pos_str = f"world_pos=({pos[0]:+.3f},{pos[1]:+.3f},{pos[2]:+.3f})"
            except Exception:
                pos_str = "(no xform)"
            # Only print non-robot collision prims (the robot has 200+
            # collision geoms which would drown out the signal).
            if "/World/Centipede/" not in path:
                print(f"  {path}  type={ptype}  {pos_str}", flush=True)
    print(f"[DIAG] total collision prims (incl. robot): {coll_count}",
          flush=True)

    # Position the camera AFTER reset so the sensor is fully initialized.
    # In chase mode we re-seat the pivot at the robot's actual reset-time
    # root position; in static mode this is a no-op (pivot already set).
    if recorder is not None:
        if args.camera_mode == "chase":
            try:
                root_pos0 = robot.data.root_pos_w[0].cpu().numpy()
                recorder.position(root_pos0)
            except Exception as e:
                print(f"[VideoRecorder] could not seed chase pivot: {e}",
                      flush=True)
                recorder.position()
        else:
            recorder.position()
        print(f"[VideoRecorder] camera_mode={args.camera_mode}")

    print(f"\n{'='*60}")
    print(f"Articulation loaded: {robot.num_joints} joints, {robot.num_bodies} bodies")
    print(f"{'='*60}")

    # ── Load controller config ──
    config_path = os.path.join(BASE_DIR, "configs", "farms_controller.yaml")
    if not os.path.isfile(config_path):
        config_path = os.path.join(BASE_DIR, "..", "Centipede_MUJOCO-main",
                                   "configs", "farms_controller.yaml")
    if not os.path.isfile(config_path):
        print(f"ERROR: Config file not found.")
        print(f"Copy farms_controller.yaml to {BASE_DIR}/configs/")
        sim_app.close()
        sys.exit(1)

    from controllers.impedance_controller import ImpedanceTravelingWaveController
    controller = ImpedanceTravelingWaveController(robot, config_path)

    # Stand-still diagnostic: zero the body & leg wave amplitudes AFTER
    # construction. The controller's impedance + heading-servo + pitch/
    # roll-hold logic all still runs, so the robot holds its neutral
    # pose — but there is no traveling wave, no leg swing. Useful for
    # isolating render-pipeline issues from locomotion-controller issues.
    if args.stand:
        # Stand mode = TRUE neutral hold. We disable every torque path
        # that produces non-zero target or non-uniform gain, leaving only
        # soft uniform impedance (body_kp, pitch_kp, roll_kp, leg_kp) to
        # damp out any startup motion and hold the rest pose.
        #
        # Why each line: in PhysX, contact dynamics excite higher-freq
        # modes than MuJoCo. The default config has STIFF gains on
        # specific head joints (body_kp_head=2.0, head_pitch_kp=0.20)
        # that, with nothing else loaded against them in stand mode,
        # oscillate visibly and rotate the body via heading-servo
        # reaction torque. Zero them out for a quiet hold.
        controller.body_amp = 0.0
        controller.leg_amps = np.zeros_like(controller.leg_amps)
        controller._leg_amp_flat = np.zeros_like(controller._leg_amp_flat)

        # CRITICAL: zero the leg DC offsets too. By default DOF 3
        # (tarsus) has dc_offset = +0.524 rad (30°). The vectorized leg
        # torque path applies dc_offsets unconditionally — even in
        # stand mode with amp=0 and blend=0 — so all 38 tarsi are
        # commanded to +30° every step, producing a constant lift on
        # the body via leg contact and bending the legs into a forced
        # pose. Zeroing it gives a true neutral leg posture.
        controller.leg_dc_offsets = np.zeros_like(controller.leg_dc_offsets)
        controller._leg_dc_flat   = np.zeros_like(controller._leg_dc_flat)

        # Heading servo OFF — no more world-frame yaw control fighting
        # any tiny yaw drift from contact.
        controller.head_yaw_gain = 0.0
        controller.head_yaw_rate = 0.0

        # Body yaw head gains demoted to plain body gains (no stiff
        # "rigid-head" zone), and amplitude envelope flat across all
        # joints.
        controller.body_kp_head = controller.body_kp
        controller.body_kv_head = controller.body_kv
        if hasattr(controller, "_build_body_kp_vec"):
            controller._build_body_kp_vec()
        # Flatten the head-end amplitude envelope too — no hold/ramp
        # zone in stand mode.
        if hasattr(controller, "body_amp_scale"):
            controller.body_amp_scale = np.ones_like(controller.body_amp_scale)

        # Pitch: zero head-pitch offset target AND demote head-pitch
        # gains to plain pitch gains.
        if hasattr(controller, "pitch_target_final"):
            controller.pitch_target_final = np.zeros_like(
                controller.pitch_target_final)
        if hasattr(controller, "pitch_kp_vec"):
            n_p = len(controller.pitch_kp_vec)
            controller.pitch_kp_vec = np.full(n_p, controller.pitch_kp, dtype=float)
            controller.pitch_kv_vec = np.full(n_p, controller.pitch_kv, dtype=float)

        print("[test_walk] --stand mode: body_amp=0, leg_amps=0, "
              "pitch_target=0, heading_servo=OFF, head_gains=demoted "
              "(true neutral hold)", flush=True)

    print(f"\nStarting walk test: {args.duration}s at dt={sim_cfg.dt}",
          flush=True)
    if recorder:
        print(f"Recording video to: {args.video}", flush=True)
    print(f"{'='*60}\n", flush=True)

    # ── DIAGNOSTIC: dump current leg joint angles so we can see whether
    #     the legs are splayed sideways (hip_yaw ≠ 0) or hanging down
    #     (hip_pitch ≠ 0) at the start of the loop.
    try:
        leg_dof_names = ["hip_yaw  (DOF 0)",
                         "hip_pitch(DOF 1)",
                         "tibia    (DOF 2)",
                         "tarsus   (DOF 3)"]
        all_pos_diag = robot.data.joint_pos[0].cpu().numpy()
        idx = controller.idx
        # Show angles of the FIRST leg, both sides — representative
        # of the rest by symmetry.
        for side_i, side in enumerate(("L", "R")):
            for dof in range(4):
                jid = idx.leg_joint_ids[0, side_i, dof]
                q = all_pos_diag[jid]
                print(f"  leg_0_{side} {leg_dof_names[dof]:<22}  "
                      f"q={np.degrees(q):+6.1f}°", flush=True)
    except Exception as e:
        print(f"[DIAG] leg-angle dump failed: {e}", flush=True)

    # ── Render warmup ────────────────────────────────────────────────
    # First sim.step(render=True) after sim.reset() can take 10+ seconds
    # while RTX compiles shaders / builds BVH. After that frames render
    # in milliseconds. Just a few warmup steps are needed to let the
    # Camera sensor's render_product produce a real (non-blank) frame.
    if recorder is not None:
        import time as _t
        n_warmup = 5
        print(f"[VideoRecorder] warmup: {n_warmup} render passes "
              f"(first one may take 10–30s while RTX initialises) …",
              flush=True)
        for i in range(n_warmup):
            t0 = _t.time()
            sim.step(render=True)
            print(f"  warmup {i+1}/{n_warmup} done in {_t.time()-t0:.1f}s",
                  flush=True)
        # First sensor read — primes _create_annotator_data().
        print("[VideoRecorder] priming camera buffers …", flush=True)
        t0 = _t.time()
        recorder.camera.update(sim_cfg.dt)
        rgb = recorder.camera.data.output.get("rgb", None)
        if rgb is None:
            print(f"[VideoRecorder] WARNING: rgb still None after warmup "
                  f"({_t.time()-t0:.1f}s)", flush=True)
        else:
            print(f"[VideoRecorder] warmup OK ({_t.time()-t0:.1f}s) — "
                  f"rgb shape={tuple(rgb.shape)} dtype={rgb.dtype}",
                  flush=True)

    # ── Simulation loop ──
    # RENDERING STRATEGY (isaaclab.sensors.Camera version):
    #   On steps where we want a video frame (or a GUI refresh), we:
    #     1. Update the camera pose if in chase mode (no-op in static).
    #     2. sim.step(render=True)  — drives the render pipeline, which
    #        populates the Camera sensor's render_product.
    #     3. recorder.camera.update(dt)  — pulls the fresh render into
    #        camera.data.output["rgb"].
    #     4. recorder.capture_frame()  — appends that tensor to the
    #        frame buffer.
    #   On other steps we use sim.step(render=False) to save ~100x on
    #   compute at dt=0.0005.
    dt = sim_cfg.dt
    n_steps = int(args.duration / dt)
    log_interval = int(1.0 / dt)

    gui_render_interval = max(1, int(1.0 / (30.0 * dt)))
    video_dt = 1.0 / args.video_fps
    last_frame_t = -np.inf

    wall_start = time.time()

    for step in range(n_steps):
        t = step * dt

        robot.update(dt)
        controller.step(t, dt)

        # Decide whether this step needs a render.
        want_video_frame = (recorder is not None
                            and (t - last_frame_t >= video_dt - 1e-10))
        want_gui_frame = ((not args.headless)
                          and (step % gui_render_interval == 0))
        do_render = want_video_frame or want_gui_frame

        # Move chase camera BEFORE the render so the frame uses the new pose.
        if do_render and recorder is not None:
            root_pos = robot.data.root_pos_w[0].cpu().numpy()
            recorder.update_camera(root_pos)

        sim.step(render=do_render)

        if want_video_frame:
            # Pull the render into the camera sensor's data buffer, then read.
            # NOTE: an earlier dual-render workaround was removed
            # because it produced ALL-black frames. The render-product
            # / Replicator annotator output appears to be cleared when
            # the next sim.step(render=True) starts; reading after
            # *two* renders gave us the half-flushed buffer (zeros).
            # The proper fix is in _set_world_pose: route the pose
            # through self.camera.set_world_poses() (Fabric write)
            # instead of UsdGeom.XformOp.Set() (USD-only write).
            recorder.camera.update(dt)
            recorder.capture_frame()
            last_frame_t = t

        # Console logging — every log_interval steps print pose so we
        # can tell hovering apart from rotating apart from oscillating.
        if step % log_interval == 0 and step > 0:
            root_pos  = robot.data.root_pos_w[0].cpu().numpy()
            root_vel  = robot.data.root_lin_vel_w[0].cpu().numpy()
            root_quat = robot.data.root_quat_w[0].cpu().numpy()  # (w,x,y,z)
            w, x, y, z = root_quat
            sinr = 2.0 * (w*x + y*z)
            cosr = 1.0 - 2.0 * (x*x + y*y)
            roll = np.degrees(np.arctan2(sinr, cosr))
            sinp = 2.0 * (w*y - z*x)
            pitch = np.degrees(np.arcsin(np.clip(sinp, -1.0, 1.0)))
            siny = 2.0 * (w*z + x*y)
            cosy = 1.0 - 2.0 * (y*y + z*z)
            yaw = np.degrees(np.arctan2(siny, cosy))
            wall_elapsed = time.time() - wall_start
            rt_ratio = t / wall_elapsed if wall_elapsed > 0 else 0
            print(f"  t={t:.1f}s  "
                  f"pos=({root_pos[0]:+.4f}, {root_pos[1]:+.4f}, "
                  f"z={root_pos[2]:+.4f})  "
                  f"vz={root_vel[2]:+.3f}  "
                  f"rpy=({roll:+5.1f}°, {pitch:+5.1f}°, {yaw:+5.1f}°)  "
                  f"[{rt_ratio:.2f}x rt]", flush=True)

    # ── Final report ──
    wall_elapsed = time.time() - wall_start
    root_pos = robot.data.root_pos_w[0].cpu().numpy()
    dist = np.sqrt(root_pos[0]**2 + root_pos[1]**2)

    print(f"\n{'='*60}")
    print(f"Walk test complete: {args.duration}s in {wall_elapsed:.1f}s wall")
    print(f"Final position: ({root_pos[0]:.4f}, {root_pos[1]:.4f}, {root_pos[2]:.4f})")
    print(f"Distance from origin: {dist:.4f}m")
    print(f"{'='*60}")

    # Save video
    if recorder:
        recorder.save()

    # GUI mode: keep window open
    if not args.headless:
        print("\nPress Ctrl+C to exit...")
        while sim_app.is_running():
            sim.step()

    sim_app.close()


if __name__ == "__main__":
    main()
