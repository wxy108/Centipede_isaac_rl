"""
impedance_controller_torch.py - torch-vectorized port of the impedance controller.
====================================================================================
Companion to controllers/impedance_controller.py (the numpy reference).

DESIGN PRINCIPLES
-----------------
1.  Same control LAW as the numpy reference, expressed as torch operations.
2.  All internal state has an explicit leading num_envs dimension; the N=1
    case must produce torque outputs that match the numpy reference modulo
    float32/float64 precision.
3.  The numpy module is the parity oracle. tests/test_controller_parity.py
    is the safety net. Do NOT edit this file without running the parity
    suite afterward.
4.  step() is PURE COMPUTE. It reads joint state from the articulation and
    RETURNS a (num_envs, num_joints) torque tensor. It does NOT call
    set_joint_effort_target / write_data_to_sim. Those are the env's job.

PORT STATUS

  [x]  Helper: quat_to_yaw           (stateless)
  [x]  Helper: pd_torque             (stateless)
  [x]  Helper: kuramoto_body_step    (per-env-broadcast aware)
  [x]  Helper: kuramoto_leg_step     (per-env-broadcast aware)
  [x]  Helper: build_body_amp_scale  (head-end cosine taper)
  [x]  Helper: seg_blend             (sequential per-segment blend)
  [x]  Class: __init__               (parameter loading, state allocation)
  [x]  Class: heading servo
  [x]  Class: body wave + PD torque
  [x]  Class: pitch + PD torque
  [x]  Class: roll  + PD torque
  [x]  Class: legs  + PD torque
  [x]  Class: step()                 (returns torque tensor)
  [x]  Class: reset_target_history(), set_frequency()
"""

